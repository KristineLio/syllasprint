const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const ctx = {console, Date, Math, Set};
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const name of ['canvas','core']) vm.runInContext(fs.readFileSync(path.join(root, 'js', name + '.js'), 'utf8'), ctx);
const B = ctx.SyllaCanvas, C = ctx.SyllaCore;
let state = C.emptyState();
assert.equal(state.boards.length, 0);
const legacy = JSON.parse(JSON.stringify(state));
delete legacy.boards;
assert.equal(C.cleanState(legacy).boards.length, 0);
state.courses.push({id:'course1',name:'Networks'}, {id:'course2',name:'Python'});
state.topics.push({id:'topic1',courseId:'course1',name:'Routers'}, {id:'topic2',courseId:'course1',name:'Switches'});
const board = B.board(state,'course1');
const a = B.addNote(board,'Router','Forwards IP packets','mint',40,50);
const b = B.addNote(board,'Switch','Forwards Ethernet frames','sky',350,50);
assert.equal(B.link(board,a.id,b.id),true);
assert.equal(B.link(board,a.id,b.id),false);
assert.equal(board.links.length,1);
B.move(board,a.id,-100,9999);
assert.equal(a.x,0);
assert.equal(a.y,B.HEIGHT-B.CARD_H);
B.updateNote(board,a.id,{title:'Router',body:'Routes between IP networks.',color:'peach'});
assert.equal(a.body,'Routes between IP networks.');
assert.equal(B.removeNote(board,a.id),true);
assert.equal(board.links.length,0);
assert.equal(B.fromTopics(state,'course1'),2);
assert.equal(B.fromTopics(state,'course1'),0);
assert.equal(board.links.length,2);
const question={id:'q1',courseId:'course1',prompt:'Explain DHCP',answer:'Automatically assigns IP settings',type:'short'};
state.questions.push(question);
assert.equal(B.pinQuestion(state,question).sourceQuestionId,'q1');
B.pinQuestion(state,question);
assert.equal(board.nodes.filter(n=>n.sourceQuestionId==='q1').length,1);
const backup=C.cleanState(JSON.parse(JSON.stringify(state)));
assert.equal(backup.boards[0].nodes.length,board.nodes.length);
const corrupt=JSON.parse(JSON.stringify(state));
corrupt.boards[0].nodes[0].body='x'.repeat(1301);
assert.throws(()=>C.cleanState(corrupt),/canvas/);
const other=B.board(state,'course2');
B.addNote(other,'Classes','Objects are class instances','cream',20,20);
C.deleteCourse(state,'course1');
assert.equal(state.boards.length,1);
assert.equal(state.boards[0].courseId,'course2');
C.deleteCourse(state,'course2');
assert.equal(state.boards.length,0);
console.log('Canvas tests passed: create, edit, move, link, topic map, pin question, persistence, backup validation, course deletion.');
