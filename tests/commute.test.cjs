const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const sandbox={Date,Math,Set,JSON,console,setTimeout,clearTimeout};
vm.runInNewContext(fs.readFileSync(__dirname+'/../js/core.js','utf8'),sandbox);
vm.runInNewContext(fs.readFileSync(__dirname+'/../js/commute.js','utf8'),sandbox);
const C=sandbox.SyllaCore,M=sandbox.SyllaCommute;
const state=C.emptyState();const cid=C.addDemo(state);
assert.equal(M.queue(state,cid,5).length,6);
assert.equal(M.queue(state,cid,10).length,10);
assert.equal(M.queue(state,cid,15).length,10);
const weak=state.questions[3];C.addAttempt(state,'exam',weak,weak.options.find(x=>x!==weak.answer),'high',false);
assert.equal(M.queue(state,cid,5)[0],weak.id,'weak exam questions must have priority');
const saved=state.questions[6];assert(M.toggleSaved(state,saved.id));
const q=M.queue(state,cid,5);assert.equal(q[0],weak.id);assert.equal(q[1],saved.id);
const now=Date.now(),session=M.begin(state,cid,5,now);
assert.equal(M.active(state),session);assert.equal(M.remaining(session,now),300);
assert.throws(()=>M.begin(state,cid,5,now),/Finish your existing/);
assert.equal(M.advance(state,session,'gotit',now),false,'cannot self-grade an unrevealed card');
assert.equal(M.reveal(session),true);
assert.equal(M.advance(state,session,'again',now),true);
assert.equal(M.saved(state,weak.id),true);
assert.equal(session.reviews[0].gradingMethod,'self-reported');
const q2=M.currentQuestion(state,session);assert.equal(q2.id,saved.id);
assert.equal(M.advance(state,session,'skip',now+1000),true);
assert.equal(session.skipped.length,1);
assert.equal(M.reveal(session),true);M.advance(state,session,'gotit',now+2000);
assert.equal(M.stats(session).gotit,1);
assert.equal(C.computeStats(state).accuracy,0,'commute self-ratings must not affect exam accuracy');
const backup=JSON.parse(JSON.stringify(state)),restore=C.cleanState(backup);
assert.equal(restore.commute.sessions.length,1);
assert.equal(restore.commute.savedQuestionIds.length,2);
const legacy=JSON.parse(JSON.stringify(backup));delete legacy.commute;
assert.equal(C.cleanState(legacy).commute.sessions.length,0,'legacy backup must import');
assert.equal(M.speechText(q2).question,q2.prompt);
M.end(state,session,now+5000);assert.equal(M.active(state),null);
C.removeDemo(state);assert.equal(M.ensure(state).sessions.length,0);assert.equal(M.ensure(state).savedQuestionIds.length,0);
assert.throws(()=>M.begin(state,cid,7),/existing course/);
console.log('Commute tests passed: queue priority, timed sessions, saved difficult cards, self-reported reviews, legacy backup and deletion.');
