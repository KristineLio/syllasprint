const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const source=fs.readFileSync(__dirname+'/../js/core.js','utf8');
const sandbox={console,Date,Math,Set,JSON};
vm.runInNewContext(source,sandbox);
const C=sandbox.SyllaCore;
const s=C.emptyState();
const id=C.addDemo(s);
assert.equal(s.courses.length,1);
assert.equal(s.questions.length,10);
assert.equal(s.materials.length,1);
const quiz=s.questions[0];
assert.equal(quiz.options.length,4);
assert(quiz.options.includes(quiz.answer));
const a=C.addAttempt(s,'session1',quiz,quiz.options.find(x=>x!==quiz.answer),'high',false);
assert.equal(a.correct,false);
assert.equal(C.isGap(s,quiz),true);
assert.equal(C.computeStats(s).gaps,1);
C.addAttempt(s,'session2',quiz,quiz.answer,'high',false);
assert.equal(C.isGap(s,quiz),false);
assert.equal(C.isWeak(s,quiz),false);
assert.equal(C.computeStats(s).accuracy,50);
const parsed=C.parseMaterial('DNS :: Name resolution\nDHCP :: IP settings\nTCP :: Reliable transport\nUDP :: Datagram transport\nQ: What is a stack?\nA: Last in first out.', 'courseA','topic1','source1');
assert.equal(parsed.length,5);
assert.equal(parsed.filter(q=>q.type==='mcq').length,4);
assert.equal(parsed.filter(q=>q.type==='short').length,1);
for(const q of parsed.filter(q=>q.type==='mcq')) {assert.equal(q.options.length,4);assert.equal(new Set(q.options).size,4);assert(q.options.includes(q.answer));}
assert.equal(C.parseMaterial('General unstructured paragraph.','c','t','s').length,0);
assert.throws(()=>C.cleanState({schemaVersion:1,courses:[]}),/required collections/);
const clean=C.cleanState(JSON.parse(JSON.stringify(s)));
assert.equal(clean.courses.length,1);
C.removeDemo(s);assert.equal(s.courses.length,0);assert.equal(s.questions.length,0);assert.equal(s.attempts.length,0);
console.log('Core tests passed: demo, scoring, confidence-gap resolution, parsing, backup validation, demo reset.');