const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const ctx={console,Date,Math,Set};ctx.globalThis=ctx;vm.createContext(ctx);
for(const name of ['canvas','core'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../js',name+'.js'),'utf8'),ctx);
const B=ctx.SyllaCanvas,C=ctx.SyllaCore,s=C.emptyState();
s.courses.push({id:'c1',name:'Python'},{id:'c2',name:'Other'});
s.topics.push({id:'t1',courseId:'c1',name:'Classes'});
s.materials.push({id:'m1',courseId:'c1',topicId:'t1',title:'OOP Lecture',content:'[[Page 2]]\nEncapsulation keeps data private.\n[[Page 3]]\nA class defines objects.'});
const q={id:'q1',courseId:'c1',topicId:'t1',sourceId:'m1',sourcePage:3,sourceExcerpt:'Page 3 · A class defines objects.',prompt:'What is a class?',answer:'A blueprint',type:'mcq',options:['A blueprint','A value']};
s.questions.push(q);
const b=B.board(s,'c1');assert.equal(B.fromTopics(s,'c1'),1);
const n=b.nodes.find(x=>x.topicId==='t1');assert.equal(n.sourceId,'m1');
assert.equal(B.relatedQuestions(s,'c1',n)[0].id,'q1');
assert.equal(B.noteStatus(s,'c1',n).gaps,0);
const pin=B.pinQuestion(s,q);assert.equal(B.sourceFor(s,'c1',pin).page,3);
const manual=B.addNote(b,'Encapsulation','Test','mint',20,20,{topicId:'t1',sourceId:'m1',sourcePage:2});
assert.equal(B.sourceFor(s,'c1',manual).excerpt,'Encapsulation keeps data private.');
s.attempts.push({questionId:'q1',correct:false,confidence:'high'});
assert.equal(B.noteStatus(s,'c1',pin).gaps,1);
s.attempts.push({questionId:'q1',correct:true,confidence:'low'});
assert.equal(B.noteStatus(s,'c1',n).gaps,0);
const old=JSON.parse(JSON.stringify(s));delete old.boards[0].nodes[0].sourceId;delete old.boards[0].nodes[0].sourcePage;
assert.equal(C.cleanState(old).boards.length,1);
const bad=JSON.parse(JSON.stringify(s));bad.boards[0].nodes[0].sourcePage=200;
assert.throws(()=>C.cleanState(bad),/canvas/);
assert.equal(B.relatedQuestions(s,'c2',n).length,0);
console.log('Concept Map regression tests passed.');
